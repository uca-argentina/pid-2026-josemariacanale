/** Emoji de un Día festivo por su nombre en castellano; 📅 si ninguna palabra clave coincide. */
export function getHolidayEmoji(holidayName: string): string {
    const name = holidayName.toLowerCase();
    return HOLIDAY_EMOJI_MAP.find(({ keywords }) => keywords.some((keyword) => name.includes(keyword)))?.emoji ?? '📅';
}
